#!/usr/bin/env node
/**
 * Copies just the font files the launcher window needs (from @fontsource in web/)
 * into ui/fonts and writes ui/fonts/fonts.css. The launcher shows before the server
 * starts, so it cannot load fonts over HTTP. The Android launcher passes its own
 * output folder as the first argument.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..', '..');
const fontsource = path.join(root, 'web', 'node_modules', '@fontsource');
const out = process.argv[2] ? path.resolve(process.argv[2]) : path.join(here, '..', 'ui', 'fonts');

// Every character the launcher UI can display.
const TEXT =
  'クリームソーダ cream roleplay soda Cream Soda ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 .,:;!?«»—–-·…()[]/+%№' +
  'АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯабвгдеёжзийклмнопрстуфхцчшщъыьэюя';
const NEED = new Set([...TEXT].map((c) => c.codePointAt(0)));

const FACES = [
  ['nunito', '600'],
  ['nunito', '700'],
  ['nunito', '800'],
  ['m-plus-rounded-1c', '800'],
  ['playfair-display', '400-italic'],
  ['jetbrains-mono', '400'],
];

function parseRanges(range) {
  return range.split(',').map((r) => {
    const [a, b] = r.trim().replace(/^U\+/i, '').split('-');
    const lo = parseInt(a, 16);
    return [lo, b ? parseInt(b, 16) : lo];
  });
}

if (!fs.existsSync(fontsource)) {
  console.error('Не найден web/node_modules/@fontsource — выполните npm install в корне проекта');
  process.exit(1);
}
fs.mkdirSync(out, { recursive: true });

let css = '/* Generated by scripts/prepare-fonts.mjs */\n';
let copied = 0;
for (const [family, weight] of FACES) {
  const file = path.join(fontsource, family, `${weight}.css`);
  const src = fs.readFileSync(file, 'utf8');
  for (const block of src.match(/@font-face\s*\{[^}]+\}/g) || []) {
    const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1];
    const woff2 = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)?.[1];
    if (!range || !woff2) continue;
    const ranges = parseRanges(range);
    const hit = [...NEED].some((cp) => ranges.some(([lo, hi]) => cp >= lo && cp <= hi));
    if (!hit) continue;
    fs.copyFileSync(path.join(fontsource, family, 'files', woff2), path.join(out, woff2));
    copied++;
    css += `${block
      .replace(/src:[^;]+;/, `src: url(./${woff2}) format('woff2');`)
      .replace(/\n\s*/g, ' ')}\n`;
  }
}
fs.writeFileSync(path.join(out, 'fonts.css'), css);
console.log(`[fonts] скопировано файлов: ${copied}`);
